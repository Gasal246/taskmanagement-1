test('shared team grants read/edit/schedule/list access and preserves action ownership', async () => {
  const target = await create({});
  const e = enquiries[0].toObject();
  for (const user of [staff, other]) {
    assert.equal(await access.canReadEnquiry(e, actor(user)), true);
    assert.equal(await access.canEditEnquiry(e, actor(user)), true);
    assert.equal(await access.canScheduleAction(e, actor(user)), true);
    const enriched = (await enrichEnquiries([e], actor(user)))[0];
    assert.equal(enriched.canRecordAction, true); assert.equal(enriched.canAdminister, false);
    assert.equal((await Eq.aggregate(staffEnquiryVisibilityStages(user._id, {}))).length, 2);
    assert.equal((await Eq.aggregate(access.enquiryVisibilityStages(actor(user)))).length, 2);
  }
  assert.equal((await enrichEnquiries([{ ...e, is_active: false }], actor(staff)))[0].canRecordAction, false);
  const action = await Histories.create({ enquiry_id: e._id, action: 'Visit', change_type: 'FORWARD', assigned_to: [other._id], action_assignments: [{ user_id: other._id, status: 'pending', revision: 1 }] });
  await assert.rejects(transitionAction({ enquiry_id: String(e._id), action_id: String(action._id), assignee_id: String(other._id), operation: 'complete', performed_action: 'Visit', notes: 'Done', expected_revision: 1 }, actor(staff)), { status: 403 });
  assert.equal((await enrichEnquiries([e], actor(staff)))[0].actions[0].action_assignments[0].can_complete, false);
  await Histories.deleteOne({ _id: action._id });
  await Targets.updateOne({ _id: target._id }, { $pull: { assigned_user_ids: staff._id } });
  assert.equal(await access.canReadEnquiry(e, actor(staff)), false);
  assert.equal(await access.canScheduleAction(e, actor(staff)), false);
  assert.equal((await Eq.aggregate(staffEnquiryVisibilityStages(staff._id, {}))).length, 0);
  await Access.create({ enquiry_id: e._id, user_id: other._id });
  await Targets.deleteOne({ _id: target._id });
  assert.equal(await access.canReadEnquiry(e, actor(other)), true);
  assert.equal(await access.canScheduleAction(e, actor(other)), false);
  await Access.deleteMany({});
});
